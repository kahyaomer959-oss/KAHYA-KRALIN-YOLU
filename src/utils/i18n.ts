export const t = (key: string, lang: string = 'Türkçe'): string => {
  const dict = translations[lang as Language] || translations['Türkçe'];
  return dict[key] || translations['English']?.[key] || translations['Türkçe']?.[key] || key;
};

export const getCountryName = (countryName: string, lang: string = 'Türkçe'): string => {
  if (lang === 'Arapça') {
    return countryArabicNameMap[countryName] || countryName;
  }
  if (lang === 'English') {
    return countryNameMap[countryName] || countryName;
  }
  return countryName;
};


export interface LogEntry {
  tr: string;
  en: string;
  ar?: string;
}

export const formatLog = (log: LogEntry | string, lang: string = 'Türkçe'): string => {
  if (typeof log === 'string') return log;
  if (lang === 'English') return log.en || log.tr;
  if (lang === 'Arapça') return log.ar || log.en || log.tr;
  return log.tr || log.en;
};

export const translateMonth = (monthName: string, lang: string = 'Türkçe'): string => {
  const monthsTr = ['Ocak', 'Şubat', 'Mart', 'Nisan', 'Mayıs', 'Haziran', 'Temmuz', 'Ağustos', 'Eylül', 'Ekim', 'Kasım', 'Aralık'];
  const monthsEn = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
  const monthsAr = ['يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو', 'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر'];

  let idx = monthsTr.indexOf(monthName);
  if (idx === -1) idx = monthsEn.indexOf(monthName);
  if (idx === -1) idx = monthsAr.indexOf(monthName);
  if (idx === -1) return monthName;

  if (lang === 'English') return monthsEn[idx];
  if (lang === 'Arapça') return monthsAr[idx];
  return monthsTr[idx];
};

